export const DICTS = { zh: ZH, en: EN }

let translator: Translate = createTranslator('zh')

export function setTranslator(locale: string): void {
  translator = createTranslator(locale)
}

export function t(key: string, params?: Record<string, string | number>): string {
  return translator(key, params)
}

export function createTranslator(locale: string): Translate {
  const dict = locale.toLowerCase().startsWith('en') ? EN : ZH
  return (key, params) => {
    const template = dict[key] ?? ZH[key] ?? key
    if (!params) return template
    return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? `{${name}}`))
  }
}
